using System.Collections.Concurrent;
using System.IO.Compression;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace MinecraftHost.Core;

public sealed record TransferProgress(string Stage, double Fraction, string Detail);

/// <summary>A plugin that the importing PC downloads instead of the package carrying it.</summary>
public sealed record PackageDownload(string Path, string Url, string Sha1, long Size, DateTime Modified);

public sealed class PackageManifest
{
    public int Format { get; set; } = 1;
    public DateTime Created { get; set; }
    public string FromPc { get; set; } = "";
    public HostConfig Config { get; set; } = new();
    public List<PackageDownload> Downloads { get; set; } = new();
    public int RegionFiles { get; set; }
    public int Files { get; set; }
    /// <summary>Size of everything once unpacked, for the free-space check.</summary>
    public long TotalBytes { get; set; }
    public List<string> LeftOut { get; set; } = new();
}

/// <summary>
/// Moves a whole server to another PC as one .mchost file (a zip):
///   manifest.json   the app's settings, and plugins to download from Modrinth
///   files/...       everything else in the server folder, as it is
///   regions/....mcz world region files, repacked losslessly (see <see cref="RegionPack"/>)
/// </summary>
public static class Transfer
{
    public const string Extension = ".mchost";

    // regenerated by the server or plugins, or only history: not worth moving
    static readonly string[] LeftOutTop = { "bluemap", "cache", ".cache", "libraries", "versions", "logs", "crash-reports", "safe-mode-plugins", "debug" };
    static readonly Regex LeftOutAnywhere = new(@"(^|/)(session\.lock|[^/]+\.part)$|^plugins/\.paper-remapped/", RegexOptions.IgnoreCase);
    static readonly Regex PluginJar = new(@"^(plugins|disabled/plugins|disabled-until[^/]*/plugins)/[^/]+\.jar$", RegexOptions.IgnoreCase);
    static readonly Regex AlreadyCompressed = new(@"\.(zip|jar|png|jpg|gz|mcz|ogg|7z|xz|br)$", RegexOptions.IgnoreCase);

    static readonly JsonSerializerOptions Json = new() { WriteIndented = true, PropertyNameCaseInsensitive = true };

    sealed record SourceFile(string FullPath, string Rel, long Size, DateTime Modified);

    static List<SourceFile> Collect(string serverDir)
    {
        var list = new List<SourceFile>();
        foreach (var path in Directory.EnumerateFiles(serverDir, "*", new EnumerationOptions { RecurseSubdirectories = true, AttributesToSkip = 0, IgnoreInaccessible = true }))
        {
            var rel = Path.GetRelativePath(serverDir, path).Replace('\\', '/');
            var top = rel.Split('/')[0];
            if (rel.Contains('/') && LeftOutTop.Contains(top, StringComparer.OrdinalIgnoreCase)) continue;
            if (LeftOutAnywhere.IsMatch(rel)) continue;
            var info = new FileInfo(path);
            list.Add(new SourceFile(path, rel, info.Length, info.LastWriteTimeUtc));
        }
        return list;
    }

    /// <summary>
    /// Package size: Likely is shown to the user, WorstCase is used for the free-space check.
    /// (Measured on a real 22 GB server: regions packed to 42%, everything else to 22%.)
    /// </summary>
    public static (long Source, long Likely, long WorstCase) Estimate(string serverDir)
    {
        var files = Collect(serverDir);
        bool Region(SourceFile f) => f.Rel.EndsWith(".mca", StringComparison.OrdinalIgnoreCase);
        long source = files.Sum(f => f.Size);
        long likely = files.Sum(f => Region(f) ? f.Size * 45 / 100 : f.Size * 35 / 100);
        long worst = files.Sum(f => Region(f) ? f.Size * 60 / 100 : f.Size);
        return (source, likely, worst);
    }

    // ------------------------------------------------------------ export

    public static async Task<PackageManifest> ExportAsync(string serverDir, HostConfig config, string packagePath,
        IProgress<TransferProgress> progress, CancellationToken ct)
    {
        progress.Report(new("Looking at the server folder...", 0, ""));
        var files = await Task.Run(() => Collect(serverDir), ct);
        var manifest = new PackageManifest
        {
            Created = DateTime.Now,
            FromPc = Environment.MachineName,
            Config = CopyConfig(config),
            LeftOut = LeftOutTop.Where(d => Directory.Exists(Path.Combine(serverDir, d))).Select(d => d + "\\").ToList(),
            TotalBytes = files.Sum(f => f.Size),
        };

        // plugins Modrinth knows by hash are downloaded on the new PC instead of carried
        progress.Report(new("Looking plugins up on Modrinth...", 0, ""));
        var jars = files.Where(f => PluginJar.IsMatch(f.Rel)).ToList();
        var downloadable = await FindDownloadsAsync(jars, ct);
        manifest.Downloads = downloadable.Values.ToList();
        files = files.Where(f => !downloadable.ContainsKey(f.Rel)).ToList();

        var regions = files.Where(f => f.Rel.EndsWith(".mca", StringComparison.OrdinalIgnoreCase)).OrderByDescending(f => f.Size).ToList();
        var others = files.Except(regions).ToList();
        manifest.RegionFiles = regions.Count;
        manifest.Files = others.Count;

        long total = files.Sum(f => f.Size), done = 0;
        var sw = System.Diagnostics.Stopwatch.StartNew();
        void Report(string stage)
        {
            var d = Interlocked.Read(ref done);
            var rate = d / Math.Max(1, sw.Elapsed.TotalSeconds);
            var left = rate > 0 ? TimeSpan.FromSeconds((total - d) / rate) : TimeSpan.Zero;
            progress.Report(new(stage, (double)d / Math.Max(1, total),
                $"{d / 1048576.0:N0} of {total / 1048576.0:N0} MB" + (d > total / 50 ? $"  ·  about {Minutes(left)} left" : "")));
        }

        var temp = packagePath + ".part";
        try
        {
            await Task.Run(() =>
            {
                using var stream = new FileStream(temp, FileMode.Create, FileAccess.Write, FileShare.None, 1 << 20);
                using var zip = new ZipArchive(stream, ZipArchiveMode.Create);

                // worlds: repack regions on all cores, write them to the zip one at a time
                using var queue = new BlockingCollection<(SourceFile File, byte[] Data, bool Packed)>(boundedCapacity: 32);
                var packer = Task.Run(() =>
                {
                    try
                    {
                        Parallel.ForEach(regions, new ParallelOptions { MaxDegreeOfParallelism = Workers, CancellationToken = ct }, f =>
                        {
                            var bytes = File.ReadAllBytes(f.FullPath);
                            var packed = RegionPack.Pack(bytes);
                            queue.Add((f, packed ?? bytes, packed != null), ct);
                        });
                    }
                    finally { queue.CompleteAdding(); }
                }, ct);

                var lastReport = DateTime.MinValue;
                foreach (var (f, data, packed) in queue.GetConsumingEnumerable(ct))
                {
                    var entry = zip.CreateEntry(packed ? $"regions/{f.Rel}.mcz" : $"files/{f.Rel}",
                        packed ? CompressionLevel.NoCompression : CompressionLevel.Optimal);
                    entry.LastWriteTime = f.Modified.ToLocalTime();
                    using (var es = entry.Open()) es.Write(data);
                    Interlocked.Add(ref done, f.Size);
                    if ((DateTime.Now - lastReport).TotalMilliseconds > 200) { Report("Packing worlds..."); lastReport = DateTime.Now; }
                }
                packer.GetAwaiter().GetResult();   // rethrow a packing error

                // everything else as it is
                foreach (var f in others)
                {
                    ct.ThrowIfCancellationRequested();
                    var entry = zip.CreateEntry($"files/{f.Rel}",
                        AlreadyCompressed.IsMatch(f.Rel) ? CompressionLevel.NoCompression : f.Size > 64 << 20 ? CompressionLevel.Fastest : CompressionLevel.Optimal);
                    entry.LastWriteTime = f.Modified.ToLocalTime();
                    using (var src = new FileStream(f.FullPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite, 1 << 20))
                    using (var es = entry.Open())
                        CopyWithProgress(src, es, n => { Interlocked.Add(ref done, n); if ((DateTime.Now - lastReport).TotalMilliseconds > 200) { Report($"Packing {f.Rel}..."); lastReport = DateTime.Now; } }, ct);
                }

                var m = zip.CreateEntry("manifest.json", CompressionLevel.Optimal);
                using (var ms = m.Open()) JsonSerializer.Serialize(ms, manifest, Json);
            }, ct);
            File.Move(temp, packagePath, overwrite: true);
        }
        catch
        {
            try { File.Delete(temp); } catch { }
            throw;
        }
        progress.Report(new("Done", 1, ""));
        return manifest;
    }

    static string Minutes(TimeSpan t) => t.TotalMinutes >= 1.5 ? $"{t.TotalMinutes:N0} min" : $"{Math.Max(5, t.TotalSeconds):N0} s";

    static void CopyWithProgress(Stream src, Stream dst, Action<long> advanced, CancellationToken ct)
    {
        var buffer = new byte[1 << 20];
        int n;
        while ((n = src.Read(buffer)) > 0)
        {
            ct.ThrowIfCancellationRequested();
            dst.Write(buffer, 0, n);
            advanced(n);
        }
    }

    static HostConfig CopyConfig(HostConfig c)
    {
        var copy = JsonSerializer.Deserialize<HostConfig>(JsonSerializer.Serialize(c))!;
        copy.ServerDir = null;   // the folder is chosen on the new PC
        copy.Servers = new();     // only this server goes in the file, not the other servers this PC manages
        copy.CurrentServerId = null;
        return copy;
    }

    // packing is CPU-bound; each worker can hold ~150 MB for a big region, so allow one per 1.5 GB of memory
    static int Workers => Math.Max(1, Math.Min(Environment.ProcessorCount - 2,
        (int)(GC.GetGCMemoryInfo().TotalAvailableMemoryBytes / (1536L << 20))));

    /// <summary>Jars whose exact file Modrinth has, with the link to that file. Empty if Modrinth can't be reached.</summary>
    static async Task<Dictionary<string, PackageDownload>> FindDownloadsAsync(List<SourceFile> jars, CancellationToken ct)
    {
        var result = new Dictionary<string, PackageDownload>();
        if (jars.Count == 0) return result;
        var bySha = new Dictionary<string, List<SourceFile>>();
        foreach (var j in jars)
        {
            ct.ThrowIfCancellationRequested();
            var sha = Net.HashFile(j.FullPath, "SHA1");
            if (!bySha.TryGetValue(sha, out var l)) bySha[sha] = l = new();
            l.Add(j);
        }
        JsonObject? known;
        try
        {
            known = await Net.PostJsonAsync("https://api.modrinth.com/v2/version_files", new { hashes = bySha.Keys.ToArray(), algorithm = "sha1" }) as JsonObject;
        }
        catch { return result; }   // offline: carry every jar instead
        if (known == null) return result;

        foreach (var (sha, list) in bySha)
        {
            var file = (known[sha]?["files"] as JsonArray)?.OfType<JsonObject>()
                .FirstOrDefault(f => f["hashes"]?["sha1"]?.GetValue<string>() == sha);
            var url = file?["url"]?.GetValue<string>();
            if (url == null) continue;
            foreach (var j in list) result[j.Rel] = new PackageDownload(j.Rel, url, sha, j.Size, j.Modified);
        }
        return result;
    }

    // ------------------------------------------------------------ import

    public static PackageManifest ReadManifest(string packagePath)
    {
        using var zip = ZipFile.OpenRead(packagePath);
        var entry = zip.GetEntry("manifest.json") ?? throw new InvalidDataException("This file isn't a server package (no manifest).");
        using var s = entry.Open();
        var m = JsonSerializer.Deserialize<PackageManifest>(s, Json) ?? throw new InvalidDataException("The package manifest is empty.");
        if (m.Format > 1) throw new InvalidDataException("This package was made by a newer version of the app. Update the app on this PC first.");
        return m;
    }

    /// <summary>Unpacks into an empty folder. Returns problems that didn't stop the import (e.g. a plugin that couldn't be downloaded).</summary>
    public static async Task<List<string>> ImportAsync(string packagePath, string serverDir,
        IProgress<TransferProgress> progress, CancellationToken ct)
    {
        var problems = new List<string>();
        var manifest = ReadManifest(packagePath);
        Directory.CreateDirectory(serverDir);
        var root = Path.GetFullPath(serverDir).TrimEnd('\\') + "\\";

        string Target(string rel)
        {
            var full = Path.GetFullPath(Path.Combine(root, rel.Replace('/', '\\')));
            if (!full.StartsWith(root, StringComparison.OrdinalIgnoreCase)) throw new InvalidDataException($"The package has an unsafe path: {rel}");
            return full;
        }

        long total = manifest.TotalBytes, done = 0;
        var sw = System.Diagnostics.Stopwatch.StartNew();
        var lastReport = DateTime.MinValue;
        void Report(string stage, bool force = false)
        {
            if (!force && (DateTime.Now - lastReport).TotalMilliseconds < 200) return;
            lastReport = DateTime.Now;
            var d = Interlocked.Read(ref done);
            var rate = d / Math.Max(1, sw.Elapsed.TotalSeconds);
            var left = rate > 0 ? TimeSpan.FromSeconds((total - d) / rate) : TimeSpan.Zero;
            progress.Report(new(stage, (double)d / Math.Max(1, total),
                $"{d / 1048576.0:N0} of {total / 1048576.0:N0} MB" + (d > total / 50 ? $"  ·  about {Minutes(left)} left" : "")));
        }

        await Task.Run(() =>
        {
            using var zip = ZipFile.OpenRead(packagePath);

            // worlds: read entries one at a time, rebuild and verify on all cores
            using var queue = new BlockingCollection<(string Rel, byte[] Data, DateTime Modified)>(boundedCapacity: 32);
            var errors = new ConcurrentQueue<string>();
            var workers = Enumerable.Range(0, Workers).Select(_ => Task.Run(() =>
            {
                foreach (var (rel, data, modified) in queue.GetConsumingEnumerable(ct))
                {
                    try
                    {
                        var mca = RegionPack.Unpack(data);
                        var path = Target(rel);
                        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                        File.WriteAllBytes(path, mca);
                        File.SetLastWriteTime(path, modified);
                        Interlocked.Add(ref done, mca.Length);
                    }
                    catch (Exception ex) { errors.Enqueue($"{rel}: {ex.Message}"); }
                }
            }, ct)).ToArray();

            try
            {
                foreach (var entry in zip.Entries.Where(e => e.FullName.StartsWith("regions/") && e.FullName.EndsWith(".mcz")))
                {
                    ct.ThrowIfCancellationRequested();
                    var data = new byte[entry.Length];
                    using (var s = entry.Open()) s.ReadExactly(data);
                    queue.Add((entry.FullName["regions/".Length..^".mcz".Length], data, entry.LastWriteTime.LocalDateTime), ct);
                    Report("Unpacking worlds...");
                }
            }
            finally { queue.CompleteAdding(); }
            Task.WaitAll(workers);
            if (!errors.IsEmpty)
                throw new InvalidDataException("Some world files failed their check, so the import was stopped:\n" + string.Join("\n", errors.Take(5)));

            foreach (var entry in zip.Entries.Where(e => e.FullName.StartsWith("files/") && !e.FullName.EndsWith("/")))
            {
                ct.ThrowIfCancellationRequested();
                var rel = entry.FullName["files/".Length..];
                var path = Target(rel);
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                using (var src = entry.Open())
                using (var dst = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None, 1 << 20))
                    CopyWithProgress(src, dst, n => { Interlocked.Add(ref done, n); Report($"Unpacking {rel}..."); }, ct);
                File.SetLastWriteTime(path, entry.LastWriteTime.LocalDateTime);
            }
        }, ct);

        // plugins from Modrinth, checked against the hash of the file that was on the old PC
        foreach (var d in manifest.Downloads)
        {
            ct.ThrowIfCancellationRequested();
            Report($"Downloading {Path.GetFileName(d.Path)}...", force: true);
            try
            {
                var path = Target(d.Path);
                await Net.DownloadAsync(d.Url, path, "SHA1", d.Sha1);
                File.SetLastWriteTimeUtc(path, d.Modified);
            }
            catch (Exception ex) { problems.Add($"{d.Path} couldn't be downloaded ({ex.Message}). Get it from {d.Url}"); }
            Interlocked.Add(ref done, d.Size);
        }
        progress.Report(new("Done", 1, ""));
        return problems;
    }
}
